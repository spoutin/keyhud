import Foundation
import AppKit

// MARK: - Markdown Exporter

struct MarkdownExporter {
    static func generateMarkdown(appName: String, groups: [ShortcutGroup]) -> String {
        var md = "# \(appName) Cheatsheet\n\n"
        md += "> Generated by KeyHUD\n\n"

        for grp in groups {
            md += "## \(grp.title)\n\n"
            md += "| Action | Shortcut |\n"
            md += "| :--- | :--- |\n"
            for item in grp.items {
                let cleanKeys = item.keys.replacingOccurrences(of: "|", with: "\\|")
                let cleanTitle = item.title.replacingOccurrences(of: "|", with: "\\|")
                md += "| \(cleanTitle) | `\(cleanKeys)` |\n"
            }
            md += "\n"
        }
        return md
    }

    static func copyToClipboard(appName: String, groups: [ShortcutGroup]) {
        let md = generateMarkdown(appName: appName, groups: groups)
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.setString(md, forType: .string)
    }

    enum ExportDestination {
        case documents
        case xdgData
    }

    static func saveToFile(appName: String, groups: [ShortcutGroup], destination: ExportDestination = .documents) -> URL? {
        let md = generateMarkdown(appName: appName, groups: groups)
        let fileManager = FileManager.default
        let targetDir: URL

        switch destination {
        case .documents:
            let docsURL = fileManager.urls(for: .documentDirectory, in: .userDomainMask).first!
            targetDir = docsURL.appendingPathComponent("KeyHUD", isDirectory: true)
        case .xdgData:
            targetDir = URL(fileURLWithPath: XDG.keyhudDataDir, isDirectory: true).appendingPathComponent("cheatsheets", isDirectory: true)
        }

        try? fileManager.createDirectory(at: targetDir, withIntermediateDirectories: true)

        let safeName = appName
            .replacingOccurrences(of: "/", with: "-")
            .replacingOccurrences(of: ":", with: "-")
            .replacingOccurrences(of: " ", with: "_")
        let fileURL = targetDir.appendingPathComponent("\(safeName)-shortcuts.md")

        do {
            try md.write(to: fileURL, atomically: true, encoding: .utf8)
            NSWorkspace.shared.activateFileViewerSelecting([fileURL])
            return fileURL
        } catch {
            return nil
        }
    }
}
